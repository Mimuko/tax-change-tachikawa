/**
 * 「支援への接続」共通セクションのデータモデル。
 *
 * 目的は、
 *  1. 制度や予算が「存在すること」
 *  2. 支援が必要な人に「実際に届いていること」
 * を分けて可視化することにある。
 *
 * このモデルは介護・教育・子育て・障害福祉・生活困窮など、
 * テーマをまたいで中身だけを差し替えて使うことを前提にしている。
 *
 * 重要な制約:
 *  - 各指標は独立した割合・数値であり、合算して「未接続率」とは表現しない。
 *  - 「未利用＝問題」「支援を利用していない人＝未接続」と単純化しない。
 *  - 接続状況を測れない場合は、そのこと自体を DataGap として明示する。
 */

/** 制度・予算の「存在」と、支援の「到達」を対比するための一組。 */
export type ExistenceDeliveryFraming = {
  /** 制度・予算が存在する側。本編で扱った内容を受ける想定。 */
  existence: {
    label: string;
    body: string;
  };
  /** 実際に届いているか、という問いの側。 */
  delivery: {
    label: string;
    body: string;
  };
};

/**
 * 単一の「接続に関する情報」。
 * 値は任意。値が無くても（＝測れなくても）指標として提示できる。
 */
export type SupportConnectionIndicator = {
  id: string;
  /** 例: 「利用したいサービスが利用できない・身近にない」 */
  label: string;
  /** 集計母数。例: 「サービス未利用者のうち」。合算不可であることを示す文脈。 */
  basis: string;
  /** 値。測れない場合は null。 */
  value: number | null;
  /** 値の単位。既定は "%"。 */
  unit?: string;
  /**
   * この数字が「何を意味するか／何を意味しないか」の短い注記。
   * 単純化を避けるための最重要フィールド。
   */
  meaning: string;
  /** 値が測れない場合に、その理由を示す。value が null のとき使用。 */
  unavailableReason?: string;
};

/**
 * 接続状況そのものを測れないことを示す注記。
 * 指標があっても「全体像は分からない」ことを添えるためにも使う。
 */
export type SupportConnectionDataGap = {
  title: string;
  body: string;
};

export type SupportConnectionData = {
  /** テーマ名。例: 「介護」 */
  theme: string;
  eyebrow: string;
  title: string;
  /** 導入文。制度と到達を分けて見る、という趣旨を述べる。 */
  lead: string;
  framing: ExistenceDeliveryFraming;
  /**
   * 指標一覧の直前に1回だけ示す、全指標に共通する集計条件。
   * 各指標に basis を繰り返さず、ここでまとめて明示する。
   */
  basisNote?: string;
  /** 指標一覧。0件でもセクションは成立する。 */
  indicators: SupportConnectionIndicator[];
  /**
   * 指標が複数回答であることなど、読み方の共通注意。
   * 「合算して未接続率とはしない」ことをここで明言する。
   */
  readingNote?: string;
  /** 接続状況を測れないことに関する注記。省略可。 */
  dataGap?: SupportConnectionDataGap;
  source?: {
    label: string;
    href?: string;
  };
};

