/**
 * 介護ストーリー本編に差し込む「支援への接続」セクションのデータ。
 *
 * 本編（給付・サービス数・支える人・保険料）は「制度の規模」を示すもので、
 * 「必要な人に届いているか」を直接示すデータではない。
 * 現時点で接続状況を継続比較できる公表データは確認できていないため、
 * 架空の割合は置かず、その「測れなさ」を DataGap として明示する。
 */
export function buildCareSupportConnection(municipalityLabel: string): SupportConnectionData {
  return {
    theme: "介護",
    eyebrow: "支援への接続",
    title: "制度はある。必要な人に、届いているか。",
    lead: `${municipalityLabel}には介護保険という制度があり、本編で見たとおり給付も受け皿も増えています。けれど「制度や予算があること」と「必要な人に支援が届いていること」は、同じではありません。`,
    framing: {
      existence: {
        label: "制度・予算はある",
        body: "介護保険制度が整い、給付総額も直近5年で増えています。市内で提供されるサービスの量も増えました。",
      },
      delivery: {
        label: "届いているかは、別の問い",
        body: "制度があることは、必要な人が実際に使えていることを保証しません。相談先・手続き・費用のどこかでつまずくと、支援は届きません。",
      },
    },
    indicators: [],
    dataGap: {
      title: "接続状況を測れる公表データは、確認できていない",
      body: `${municipalityLabel}で「支援が必要なのに介護サービスや相談につながっていない人」の規模を、継続的に測れる公表データは現時点では確認できていません。本編の給付総額やサービス数は「制度の規模」を示すもので、「必要な人に届いているか」を直接示すものではありません。確認でき次第、ここに追記します。`,
    },
  };
}

/**
 * 教育ストーリー本編に差し込む「支援への接続」セクションのデータ。
 *
 * 教職員数・学級数・教育相談件数はいずれも「体制・活動の規模」であり、
 * 「支援を必要とする子どもに届いているか」を直接示すものではない。
 * とくに相談『件数』は延べ数であって人数ではない点を読み方注記で明示する。
 */
export function buildEducationSupportConnection(municipalityLabel: string): SupportConnectionData {
  return {
    theme: "教育",
    eyebrow: "支援への接続",
    title: "制度はある。必要な子どもに、届いているか。",
    lead: `${municipalityLabel}には学校も教職員も教育相談もあり、本編で見たとおりその規模は動いています。けれど「体制があること」と「支援が必要な子どもに届いていること」は、同じではありません。`,
    framing: {
      existence: {
        label: "体制・窓口はある",
        body: "市立小中の教職員数は増え、特別支援学級も教育相談の件数も本編のとおり増えています。",
      },
      delivery: {
        label: "届いているかは、別の問い",
        body: "相談や支援の窓口があることは、支援を必要とする子どもすべてに届いていることを意味しません。入口の分かりにくさや家庭の事情で、つながれないことがあります。",
      },
    },
    indicators: [],
    readingNote:
      "教育相談の「件数」は延べの相談数であり、支援が届いた子どもの人数を示すものではありません。同じ子どもが複数回相談することも、相談に至らない子どもがいることもあります。",
    dataGap: {
      title: "接続状況を測れる公表データは、確認できていない",
      body: `${municipalityLabel}で「支援が必要な子どものうち、どれだけが相談や支援につながっているか」を継続比較できる公表データは確認できていません。市単独の不登校データが無いこととも重なります。確認でき次第、ここに追記します。`,
    },
  };
}


